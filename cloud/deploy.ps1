# Build + deploy the backend stack, write web/js/config.js from the stack
# outputs, and upload the website to the EC2 web server.
#
#   .\deploy.ps1
param(
    [string]$StackName = "smartvent",
    [string]$Region = "us-east-2",
    [string]$AssistantModel = "qwen/qwen3.8-27b"   # open-source model served by Groq
)
$ErrorActionPreference = "Stop"
Push-Location $PSScriptRoot
try {
    sam build
    if ($LASTEXITCODE -ne 0) { throw "sam build failed" }

    # --resolve-s3 lets SAM create/reuse its own bucket for the Lambda code.
    sam deploy --stack-name $StackName --region $Region --capabilities CAPABILITY_IAM `
        --resolve-s3 --no-confirm-changeset --no-fail-on-empty-changeset `
        --parameter-overrides "AssistantModel=$AssistantModel"
    if ($LASTEXITCODE -ne 0) { throw "sam deploy failed" }

    $outputs = @{}
    (aws cloudformation describe-stacks --stack-name $StackName --region $Region --query "Stacks[0].Outputs" | ConvertFrom-Json) |
        ForEach-Object { $outputs[$_.OutputKey] = $_.OutputValue }

    $config = @"
// Generated by cloud/deploy.ps1 from the CloudFormation outputs. Not secret.
window.SMARTVENT_CONFIG = {
  region: "$($outputs.Region)",
  apiUrl: "$($outputs.ApiUrl)",
  userPoolId: "$($outputs.UserPoolId)",
  clientId: "$($outputs.UserPoolClientId)"
};
"@
    $config | Out-File -Encoding utf8 ..\web\js\config.js

    & ..\server\deploy-web.ps1

    Write-Host ""
    Write-Host "API: $($outputs.ApiUrl)"
}
finally { Pop-Location }
