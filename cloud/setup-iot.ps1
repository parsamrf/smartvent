# One-time AWS IoT setup for the gateway: creates the Thing, a certificate +
# key pair, attaches the policy created by the SAM stack, and generates
# firmware/gateway/src/secrets.h (git-ignored). Run after the first deploy.
#
#   .\setup-iot.ps1 -WifiSsid "MyWifi" -WifiPassword "secret"
param(
    [Parameter(Mandatory = $true)][string]$WifiSsid,
    [Parameter(Mandatory = $true)][string]$WifiPassword,
    [string]$ThingName = "smartvent-gateway",
    [string]$PolicyName = "smartvent-gateway-policy"
)
$ErrorActionPreference = "Stop"
$certDir = Join-Path $PSScriptRoot "..\firmware\gateway\certs"
New-Item -ItemType Directory -Force $certDir | Out-Null

aws iot create-thing --thing-name $ThingName | Out-Null

$cert = aws iot create-keys-and-certificate --set-as-active `
    --certificate-pem-outfile "$certDir\device.pem.crt" `
    --private-key-outfile "$certDir\private.pem.key" | ConvertFrom-Json
aws iot attach-policy --policy-name $PolicyName --target $cert.certificateArn
aws iot attach-thing-principal --thing-name $ThingName --principal $cert.certificateArn

Invoke-WebRequest -UseBasicParsing https://www.amazontrust.com/repository/AmazonRootCA1.pem -OutFile "$certDir\AmazonRootCA1.pem"
$endpoint = aws iot describe-endpoint --endpoint-type iot:Data-ATS --query endpointAddress --output text

$ca = (Get-Content "$certDir\AmazonRootCA1.pem" -Raw).Trim()
$crt = (Get-Content "$certDir\device.pem.crt" -Raw).Trim()
$key = (Get-Content "$certDir\private.pem.key" -Raw).Trim()

@"
// Generated by cloud/setup-iot.ps1 - DO NOT COMMIT (git-ignored).
#pragma once
#define WIFI_SSID "$WifiSsid"
#define WIFI_PASSWORD "$WifiPassword"
#define AWS_IOT_ENDPOINT "$endpoint"
#define THING_NAME "$ThingName"

static const char AWS_ROOT_CA[] = R"EOF(
$ca
)EOF";

static const char DEVICE_CERT[] = R"KEY(
$crt
)KEY";

static const char DEVICE_PRIVATE_KEY[] = R"KEY(
$key
)KEY";
"@ | Out-File -Encoding ascii (Join-Path $PSScriptRoot "..\firmware\gateway\src\secrets.h")

Write-Host "Created thing '$ThingName', certificate $($cert.certificateId)"
Write-Host "Endpoint: $endpoint"
Write-Host "Wrote firmware/gateway/src/secrets.h"
